        private readonly CrowdinOtaService _otaService = CrowdinOtaService.Instance;

        public LocalizationService() {
            LoadCachedOtaTranslations(_currentLanguage);
        }

        public string CurrentLanguage {
            get => _currentLanguage;
            set {
                if (_currentLanguage != value) {
                    _currentLanguage = value;
                    LoadCachedOtaTranslations(_currentLanguage);
                    NotifyAllPropertiesChanged();
                    _ = Task.Run(async () => {
                        try {
                            await SyncOtaTranslationsAsync(_currentLanguage);
                        } catch { }
                    });
                }
            }
        }

        public async Task InitOtaAsync() {
            LoadCachedOtaTranslations(_currentLanguage);
            await SyncOtaTranslationsAsync(_currentLanguage);
        }

        public void LoadCachedOtaTranslations(string lang) {
            try {
                var cached = _otaService.LoadCachedTranslations(lang);
                if (cached != null) {
                    ApplyOtaDictionary(lang, cached);
                }
            } catch { }
        }

        public async Task<bool> SyncOtaTranslationsAsync(string lang, CancellationToken ct = default) {
            try {
                var remote = await _otaService.RefreshLanguageAsync(lang, ct);
                if (remote != null) {
                    ApplyOtaDictionary(lang, remote);
                    return true;
                }
            } catch { }
            return false;
        }

        public async Task<bool> RefreshOtaTranslationsAsync(CancellationToken ct = default) {
            return await SyncOtaTranslationsAsync(_currentLanguage, ct);
        }

        private void ApplyOtaDictionary(string lang, Dictionary<string, string> strings) {
            void SetDict(string targetLang) {
                if (!_translations.ContainsKey(targetLang)) {
                    _translations[targetLang] = new Dictionary<string, string>();
                }
                foreach (var (k, v) in strings) {
                    if (string.Equals(targetLang, "en", StringComparison.OrdinalIgnoreCase) && k == "Rename" && v == "Rename") {
                        _translations[targetLang][k] = "Edit";
                        continue;
                    }
                    _translations[targetLang][k] = v;
                }
            }

            SetDict(lang);
            if (lang.Contains('-')) {
                string shortCode = lang.Split('-')[0];
                SetDict(shortCode);
            } else if (string.Equals(lang, "hy", StringComparison.OrdinalIgnoreCase)) {
                SetDict("hy-AM");
            } else if (string.Equals(lang, "es", StringComparison.OrdinalIgnoreCase)) {
                SetDict("es-ES");
            } else if (string.Equals(lang, "zh", StringComparison.OrdinalIgnoreCase)) {
                SetDict("zh-TW");
            }

            NotifyAllPropertiesChanged();
        }

        private void NotifyAllPropertiesChanged() {
            PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(string.Empty));
            PropertyChanged?.Invoke(this, new PropertyChangedEventArgs("Item[]"));
            PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(CurrentLanguage)));
        }

        public string this[string key] {
            get {
                if (_translations.TryGetValue(_currentLanguage, out var dict) && dict.TryGetValue(key, out var val)) {
                    return val;
                }
                if (_translations["en"].TryGetValue(key, out var enVal)) {
                    return enVal;
                }
                return key;
            }
        }

        public string Get(string key) {
            return this[key];
        }

        public IReadOnlyDictionary<string, string> GetTranslations(string? langCode = null) {
            string lang = langCode ?? _currentLanguage;
            if (_translations.TryGetValue(lang, out var dict)) {
                return dict;
            }
            return _translations["en"];
        }

        public Dictionary<string, (string referenceText, string translatedText)> GetAllKeysWithTranslations(string? langCode = null) {
            string lang = langCode ?? _currentLanguage;
            var result = new Dictionary<string, (string referenceText, string translatedText)>(StringComparer.OrdinalIgnoreCase);
            var refDict = _translations["en"];
            var hyDict = _translations["hy"];
            _translations.TryGetValue(lang, out var targetDict);

            foreach (var (k, enVal) in refDict) {
                string refText = lang == "hy" ? enVal : (hyDict.TryGetValue(k, out var hyVal) ? hyVal : enVal);
                string trText = (targetDict != null && targetDict.TryGetValue(k, out var t)) ? t : this[k];
                result[k] = (refText, trText);
            }
            return result;
        }

        public (int translated, int total) GetTranslationStats(string? langCode = null) {
            string lang = langCode ?? _currentLanguage;
            int total = _translations.TryGetValue("en", out var enDict) ? enDict.Count : 0;
            int translated = 0;
            if (_translations.TryGetValue(lang, out var dict)) {
                translated = dict.Count;
            }
            return (translated, total);
        }

        public static string MapCountryCodeToLanguage(string countryCode) {
            if (string.IsNullOrWhiteSpace(countryCode)) return string.Empty;
            string cc = countryCode.Trim().ToUpperInvariant();

            if (cc == "AM") return "hy";

            string[] ruCountries = { "RU", "BY", "KZ", "KG", "TJ", "UZ", "UA", "MD" };
            if (ruCountries.Contains(cc)) return "ru";

            string[] frCountries = { "FR", "BE", "CH", "MC", "SN", "CI", "CD", "CM", "MG", "LU" };
            if (frCountries.Contains(cc)) return "fr";

            string[] esCountries = { "ES", "MX", "AR", "CO", "CL", "PE", "VE", "GT", "EC", "CU", "BO", "DO", "HN", "PY", "SV", "NI", "CR", "PA", "UY", "PR" };
            if (esCountries.Contains(cc)) return "es";

            string[] zhCountries = { "CN", "TW", "HK", "MO", "SG" };
            if (zhCountries.Contains(cc)) return "zh";

            string[] arCountries = { "SA", "EG", "AE", "IQ", "DZ", "MA", "SD", "YE", "SY", "TN", "JO", "LY", "LB", "OM", "KW", "MR", "QA", "BH", "DJ", "SO", "PS" };
            if (arCountries.Contains(cc)) return "ar";

            string[] enCountries = { "US", "GB", "CA", "AU", "NZ", "IE", "ZA", "IN" };
            if (enCountries.Contains(cc)) return "en";

            return string.Empty;
        }

        public static async Task<string> DetectOptimalLanguageAsync() {
            // 1. Check Windows UI Culture
            try {
                var uiCulture = CultureInfo.CurrentUICulture;
                string twoLetter = uiCulture.TwoLetterISOLanguageName.ToLowerInvariant();
                string[] supportedLangs = { "hy", "en", "ru", "fr", "es", "zh", "ar" };
                if (supportedLangs.Contains(twoLetter)) {
                    return twoLetter;
                }

                // Check Windows Region
                try {
                    var region = new RegionInfo(CultureInfo.CurrentCulture.LCID);
                    string mapped = MapCountryCodeToLanguage(region.TwoLetterISORegionName);
                    if (!string.IsNullOrEmpty(mapped)) {
                        return mapped;
                    }
                } catch { }
            } catch { }

            // 2. Query IP Geolocation with strict 1.5s timeout
            try {
                using var cts = new CancellationTokenSource(1500);
                using var client = new HttpClient();
                client.Timeout = TimeSpan.FromMilliseconds(1500);
                string json = await client.GetStringAsync("http://ip-api.com/json/?fields=countryCode", cts.Token);
                using var doc = JsonDocument.Parse(json);
                if (doc.RootElement.TryGetProperty("countryCode", out var ccProp)) {
                    string cc = ccProp.GetString() ?? string.Empty;
                    string mapped = MapCountryCodeToLanguage(cc);
                    if (!string.IsNullOrEmpty(mapped)) {
                        return mapped;
                    }
                }
            } catch { }

            return "en"; // Default fallback
        }
